    private void actualizarTabla() {

        javax.swing.table.DefaultTableModel modelo = (javax.swing.table.DefaultTableModel)tblProductos.getModel();

        modelo.setRowCount(0);

        for (Producto producto : inventario.getProductos()) {

            Object[] fila = {
                producto.getNombre(),
                producto.getPrecio(),
                producto.getCantidad(),
                producto.calcularSubtotal()
            };

            modelo.addRow(fila);
        }

        lblCantidadProductos.setText(String.valueOf(inventario.obtenerTotalProductos()));
        lblStockBajo.setText(String.valueOf(inventario.contarStockBajo()));
        lblTotal.setText("$" + inventario.calcularValorInventario());
    }

  
